-- CREATE TABLE IF NOT EXISTS evita substituir uma tabela que ja contenha dados.

CREATE TABLE IF NOT EXISTS CNPJ_DB.PUBLIC.EMPRESAS_BRONZE (
    CNPJ_BASICO VARCHAR,
    RAZAO_SOCIAL VARCHAR,
    NATUREZA_JURIDICA VARCHAR,
    QUALIFICACAO_RESPONSAVEL VARCHAR,
    CAPITAL_SOCIAL VARCHAR,
    PORTE_EMPRESA VARCHAR,
    ENTE_FEDERATIVO_RESPONSAVEL VARCHAR
);

