    PAIS VARCHAR(3),
    DATA_INICIO_ATIVIDADE VARCHAR(8),
    CNAE_FISCAL_PRINCIPAL VARCHAR(7),
    CNAE_FISCAL_SECUNDARIA VARCHAR(2000),
    TIPO_LOGRADOURO VARCHAR(50),
    LOGRADOURO VARCHAR(255),
    NUMERO VARCHAR(20),
    COMPLEMENTO VARCHAR(255),
