SELECT
    TRIM(CNPJ_BASICO) AS CNPJ_BASICO,
    UPPER(TRIM(RAZAO_SOCIAL)) AS RAZAO_SOCIAL,
    TRIM(NATUREZA_JURIDICA) AS NATUREZA_JURIDICA,
    TRIM(QUALIFICACAO_RESPONSAVEL) AS QUALIFICACAO_RESPONSAVEL,
    TRY_TO_DECIMAL(
        REPLACE(CAPITAL_SOCIAL, ',', '.'),
        18, 2
    ) AS CAPITAL_SOCIAL,
    TRIM(PORTE_EMPRESA) AS PORTE_EMPRESA,
    NULLIF(TRIM(ENTE_FEDERATIVO_RESPONSAVEL), '') AS ENTE_FEDERATIVO_RESPONSAVEL
FROM CNPJ_DB.PUBLIC.EMPRESAS_BRONZE
WHERE CNPJ_BASICO IS NOT NULL
  AND RAZAO_SOCIAL IS NOT NULL