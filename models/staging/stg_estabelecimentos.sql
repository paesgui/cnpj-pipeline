
SELECT
    TRIM(CNPJ_BASICO) AS CNPJ_BASICO,
    TRIM(CNPJ_ORDEM) AS CNPJ_ORDEM,
    TRIM(CNPJ_DV) AS CNPJ_DV,
    TRIM(IDENTIFICADOR_MATRIZ_FILIAL) AS IDENTIFICADOR_MATRIZ_FILIAL,
    NULLIF(UPPER(TRIM(NOME_FANTASIA)), '') AS NOME_FANTASIA,
    TRIM(SITUACAO_CADASTRAL) AS SITUACAO_CADASTRAL,
    TRY_TO_DATE(DATA_SITUACAO_CADASTRAL, 'YYYYMMDD') AS DATA_SITUACAO_CADASTRAL,
    TRIM(MOTIVO_SITUACAO_CADASTRAL) AS MOTIVO_SITUACAO_CADASTRAL,
    NULLIF(TRIM(NOME_CIDADE_EXTERIOR), '') AS NOME_CIDADE_EXTERIOR,
    NULLIF(TRIM(PAIS), '') AS PAIS,
    TRY_TO_DATE(DATA_INICIO_ATIVIDADE, 'YYYYMMDD') AS DATA_INICIO_ATIVIDADE,
    TRIM(CNAE_FISCAL_PRINCIPAL) AS CNAE_FISCAL_PRINCIPAL,
    NULLIF(TRIM(CNAE_FISCAL_SECUNDARIA), '') AS CNAE_FISCAL_SECUNDARIA,
    NULLIF(UPPER(TRIM(TIPO_LOGRADOURO)), '') AS TIPO_LOGRADOURO,
    NULLIF(UPPER(TRIM(LOGRADOURO)), '') AS LOGRADOURO,
    NULLIF(TRIM(NUMERO), '') AS NUMERO,
    NULLIF(UPPER(TRIM(COMPLEMENTO)), '') AS COMPLEMENTO,
    NULLIF(UPPER(TRIM(BAIRRO)), '') AS BAIRRO,
    NULLIF(TRIM(CEP), '') AS CEP,
    NULLIF(UPPER(TRIM(UF)), '') AS UF,
    NULLIF(TRIM(CODIGO_MUNICIPIO), '') AS CODIGO_MUNICIPIO,
    NULLIF(TRIM(DDD1), '') AS DDD1,
    NULLIF(TRIM(TELEFONE1), '') AS TELEFONE1,
    NULLIF(TRIM(DDD2), '') AS DDD2,
    NULLIF(TRIM(TELEFONE2), '') AS TELEFONE2,
    NULLIF(TRIM(DDD_FAX), '') AS DDD_FAX,
    NULLIF(TRIM(FAX), '') AS FAX,
    NULLIF(LOWER(TRIM(CORREIO_ELETRONICO)), '') AS CORREIO_ELETRONICO,
    NULLIF(TRIM(SITUACAO_ESPECIAL), '') AS SITUACAO_ESPECIAL,
    TRY_TO_DATE(DATA_SITUACAO_ESPECIAL, 'YYYYMMDD') AS DATA_SITUACAO_ESPECIAL
FROM CNPJ_DB.PUBLIC.ESTABELECIMENTOS_BRONZE
WHERE CNPJ_BASICO IS NOT NULL
  AND TRIM(CNPJ_BASICO) <> ''
