
WITH BASE AS (
    SELECT
        N.CODIGO_NATUREZA,
        N.DESCRICAO_NATUREZA,
        COUNT(*) AS TOTAL_EMPRESAS
    FROM {{ ref('stg_empresas') }} E
    INNER JOIN {{ ref('stg_naturezas') }} N
        ON E.NATUREZA_JURIDICA = N.CODIGO_NATUREZA
    GROUP BY
        N.CODIGO_NATUREZA,
        N.DESCRICAO_NATUREZA
)

SELECT
    CODIGO_NATUREZA,
    DESCRICAO_NATUREZA,
    TOTAL_EMPRESAS,

    ROUND(
        TOTAL_EMPRESAS * 100.0 /
        SUM(TOTAL_EMPRESAS) OVER (),
        2
    ) AS PARTICIPACAO_PERCENTUAL,

    DENSE_RANK() OVER (
        ORDER BY TOTAL_EMPRESAS DESC
    ) AS RANKING,

    ROUND(
        SUM(TOTAL_EMPRESAS) OVER (
            ORDER BY TOTAL_EMPRESAS DESC
            ROWS BETWEEN UNBOUNDED PRECEDING
            AND CURRENT ROW
        ) * 100.0 /
        SUM(TOTAL_EMPRESAS) OVER (),
        2
    ) AS PARTICIPACAO_ACUMULADA

FROM BASE
ORDER BY TOTAL_EMPRESAS DESC
