
SELECT
    N.CODIGO_NATUREZA,
    N.DESCRICAO_NATUREZA,
    E.PORTE_EMPRESA AS CODIGO_PORTE,

    COUNT(*) AS TOTAL_EMPRESAS,

    ROUND(MEDIAN(E.CAPITAL_SOCIAL), 2) AS CAPITAL_MEDIANO,

    ROUND(
        PERCENTILE_CONT(0.25)
        WITHIN GROUP (ORDER BY E.CAPITAL_SOCIAL), 2
    ) AS CAPITAL_P25,

    ROUND(
        PERCENTILE_CONT(0.75)
        WITHIN GROUP (ORDER BY E.CAPITAL_SOCIAL), 2
    ) AS CAPITAL_P75,

    ROUND(
        PERCENTILE_CONT(0.90)
        WITHIN GROUP (ORDER BY E.CAPITAL_SOCIAL), 2
    ) AS CAPITAL_P90

FROM {{ ref('stg_empresas') }} E

INNER JOIN {{ ref('stg_naturezas') }} N
    ON E.NATUREZA_JURIDICA = N.CODIGO_NATUREZA

WHERE E.CAPITAL_SOCIAL IS NOT NULL

GROUP BY
    N.CODIGO_NATUREZA,
    N.DESCRICAO_NATUREZA,
    E.PORTE_EMPRESA
