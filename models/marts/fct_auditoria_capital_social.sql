
SELECT
    N.CODIGO_NATUREZA,
    N.DESCRICAO_NATUREZA,
    E.PORTE_EMPRESA AS CODIGO_PORTE,

    COUNT(*) AS TOTAL_EMPRESAS,

    COUNT_IF(
        E.CAPITAL_SOCIAL = 999999999999.00
    ) AS EMPRESAS_VALOR_LIMITE_OBSERVADO,

    COUNT_IF(
        E.CAPITAL_SOCIAL >= 100000000
    ) AS EMPRESAS_CAPITAL_ELEVADO,

    COUNT_IF(
        E.CAPITAL_SOCIAL < 0
    ) AS EMPRESAS_CAPITAL_NEGATIVO,

    COUNT_IF(
        E.CAPITAL_SOCIAL IS NULL
    ) AS EMPRESAS_CAPITAL_NULO,

    ROUND(
        AVG(E.CAPITAL_SOCIAL), 2
    ) AS CAPITAL_MEDIO,

    ROUND(
        SUM(E.CAPITAL_SOCIAL), 2
    ) AS CAPITAL_TOTAL

FROM {{ ref('stg_empresas') }} E

INNER JOIN {{ ref('stg_naturezas') }} N
    ON E.NATUREZA_JURIDICA = N.CODIGO_NATUREZA

GROUP BY
    N.CODIGO_NATUREZA,
    N.DESCRICAO_NATUREZA,
    E.PORTE_EMPRESA

ORDER BY EMPRESAS_VALOR_LIMITE_OBSERVADO DESC
