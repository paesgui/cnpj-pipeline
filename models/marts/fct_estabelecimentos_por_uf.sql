SELECT
    UF,
    COUNT(*) AS TOTAL_ESTABELECIMENTOS,
    COUNT_IF(SITUACAO_CADASTRAL = '02') AS ESTABELECIMENTOS_ATIVOS,
    COUNT_IF(SITUACAO_CADASTRAL <> '02') AS ESTABELECIMENTOS_NAO_ATIVOS,
    COUNT_IF(IDENTIFICADOR_MATRIZ_FILIAL = '1') AS TOTAL_MATRIZES,
    COUNT_IF(IDENTIFICADOR_MATRIZ_FILIAL = '2') AS TOTAL_FILIAIS,
    COUNT(DISTINCT CNPJ_BASICO) AS TOTAL_EMPRESAS
FROM {{ ref('stg_estabelecimentos') }}
WHERE UF IS NOT NULL
  AND UF <> 'EX'
GROUP BY UF

