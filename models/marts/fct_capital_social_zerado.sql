
SELECT
    N.CODIGO_NATUREZA,
    N.DESCRICAO_NATUREZA,

    E.PORTE_EMPRESA AS CODIGO_PORTE,

    CASE
        WHEN NULLIF(TRIM(E.PORTE_EMPRESA), '') IS NULL
            THEN 'Não informado (campo vazio)'
        ELSE COALESCE(
            P.DESCRICAO_PORTE,
            'Código não cadastrado'
        )
    END AS DESCRICAO_PORTE,

    COUNT(*) AS TOTAL_EMPRESAS,

    COUNT_IF(E.CAPITAL_SOCIAL = 0)
        AS EMPRESAS_CAPITAL_ZERADO,

    COUNT_IF(E.CAPITAL_SOCIAL IS NULL)
        AS EMPRESAS_CAPITAL_NAO_INFORMADO,

    ROUND(
        COUNT_IF(E.CAPITAL_SOCIAL = 0) * 100.0
        / NULLIF(COUNT(*), 0),
        2
    ) AS PERCENTUAL_CAPITAL_ZERADO

FROM {{ ref('stg_empresas') }} E

INNER JOIN {{ ref('stg_naturezas') }} N
    ON E.NATUREZA_JURIDICA = N.CODIGO_NATUREZA

LEFT JOIN {{ ref('stg_portes_empresa') }} P
    ON TRIM(E.PORTE_EMPRESA) = P.CODIGO_PORTE

GROUP BY
    N.CODIGO_NATUREZA,
    N.DESCRICAO_NATUREZA,
    E.PORTE_EMPRESA,
    DESCRICAO_PORTE

ORDER BY EMPRESAS_CAPITAL_ZERADO DESC
